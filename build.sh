#!/usr/bin/env bash
# Assemble the versioned extension scripts from sql/. Run after editing anything in sql/.
#   pgkv--<version>.sql            fresh install
#   pgkv--0.3.0--<version>.sql     upgrade from 0.3.0
set -euo pipefail
cd "$(dirname "$0")"

VERSION=$(sed -n "s/^default_version = '\(.*\)'/\1/p" pgkv.control)
FUNCTIONS=(sql/1*.sql sql/2*.sql sql/3*.sql sql/4*.sql sql/5*.sql sql/6*.sql sql/7*.sql sql/8*.sql sql/9*.sql)
NOTE="-- Generated by build.sh from sql/. Do not edit: change the files in sql/ and run ./build.sh."

{
  echo '-- complain if script is sourced in psql, rather than via CREATE EXTENSION'
  echo '\echo Use "CREATE EXTENSION pgkv" to load this file. \quit'
  echo
  echo "$NOTE"
  echo
  cat sql/00-schema.sql sql/01-collections.sql "${FUNCTIONS[@]}"
} > "pgkv--${VERSION}.sql"

{
  echo '-- complain if script is sourced in psql, rather than via ALTER EXTENSION'
  echo "\\echo Use \"ALTER EXTENSION pgkv UPDATE TO '${VERSION}'\" to load this file. \\quit"
  echo
  echo "$NOTE"
  echo
  cat sql/upgrade-0.3.0.sql sql/01-collections.sql sql/upgrade-0.3.0-data.sql "${FUNCTIONS[@]}"
} > "pgkv--0.3.0--${VERSION}.sql"

echo "built pgkv--${VERSION}.sql and pgkv--0.3.0--${VERSION}.sql"
